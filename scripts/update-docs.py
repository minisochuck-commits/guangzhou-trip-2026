import pathlib
import sys


def once(path: str, a: str, b: str, note: str) -> None:
    p = pathlib.Path(path)
    text = p.read_text(encoding="utf-8")
    if text.count(a) != 1:
        print(f"✗ {note}: 命中 {text.count(a)} 次")
        sys.exit(1)
    p.write_text(text.replace(a, b, 1), encoding="utf-8")
    print(f"✓ {note}")


